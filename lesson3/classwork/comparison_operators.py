# Comparison operators compare values and return True or False
print(5 > 3) # Greater than
print(5 < 3) # Less than
print(5>=5)  # Greater than or equal to
print(5 <=5) # Less than or equal to
print(5 == 5) # Equal to
print(5 != 3)   # Not equal to

# You can compare variables to
a = 10
b = 7
print(a > b)
print(a==b)

